#!/usr/bin/env python3
"""Generate v16 -> v17 lowercase changes and v17 final-sigma properties.

Inputs are official UCD UnicodeData.txt/SpecialCasing.txt for 16.0.0 and 17.0.0,
plus 17.0.0 DerivedCoreProperties.txt. No build/startup generation is needed.
"""
import argparse
import hashlib
from pathlib import Path


def mappings(data, special):
    result = {}
    for line in data.read_text().splitlines():
        fields = line.split(";")
        if fields[13]:
            result[int(fields[0], 16)] = [int(fields[13], 16)]
    for line in special.read_text().splitlines():
        fields = line.split("#")[0].strip().split(";")
        if len(fields) >= 5 and not fields[4].strip():
            result[int(fields[0], 16)] = [int(n, 16) for n in fields[1].split()]
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("data16", type=Path)
    parser.add_argument("special16", type=Path)
    parser.add_argument("data17", type=Path)
    parser.add_argument("special17", type=Path)
    parser.add_argument("properties17", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    before = mappings(args.data16, args.special16)
    after = mappings(args.data17, args.special17)
    changes = [(n, after.get(n, [n])) for n in sorted(before.keys() | after.keys()) if before.get(n, [n]) != after.get(n, [n])]
    assert len(changes) == 28 and all(len(lower) == 1 for _, lower in changes)
    tables = {"CASED": [], "CASE_IGNORABLE": []}
    for line in args.properties17.read_text().splitlines():
        fields = line.split("#")[0].strip().split(";")
        if len(fields) != 2 or fields[1].strip().upper() not in tables:
            continue
        limits = [int(n, 16) for n in fields[0].strip().split("..")]
        tables[fields[1].strip().upper()].append((limits[0], limits[-1]))
    output = ["// Generated by generate-names.py from official Unicode UCD files.",
              "// Unicode data copyright Unicode, Inc.; see LICENSE-UNICODE."]
    for name in ["data16", "special16", "data17", "special17", "properties17"]:
        path = getattr(args, name)
        output.append(f"// {name}: SHA256 {hashlib.sha256(path.read_bytes()).hexdigest()}")
    tables["LOWER_CHANGES"] = [(n, lower[0]) for n, lower in changes]
    for name, pairs in tables.items():
        if name != "LOWER_CHANGES":
            assert pairs and all(a <= b for a, b in pairs)
            assert all(pairs[i-1][1] < pairs[i][0] for i in range(1, len(pairs)))
        output.append(f"#[rustfmt::skip]\npub(super) const {name}: &[(u32,u32)] = &[")
        for i in range(0, len(pairs), 4):
            output.append("    " + " ".join(f"(0x{a:x}, 0x{b:x})," for a, b in pairs[i:i+4]))
        output.append("];")
    args.output.write_text("\n".join(output)+"\n")


if __name__ == "__main__":
    main()
